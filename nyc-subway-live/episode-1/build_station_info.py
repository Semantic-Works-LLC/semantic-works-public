#!/usr/bin/env python3
"""Builds site/station-data.js: the facts about each station the page's Selection tab shows.

Standard library only. Reads the newest copy of the MTA's station list from
data/stations/ (see fetch_static.py).
"""
import csv
import json
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE / "site" / "station-data.js"
BOROUGHS = {"M": "Manhattan", "Bk": "Brooklyn", "Bx": "The Bronx", "Q": "Queens", "SI": "Staten Island"}
ACCESSIBLE = {"0": "Not accessible", "1": "Accessible", "2": "Partly accessible"}


def main():
    newest = sorted((HERE / "data" / "stations").glob("*.csv"))[-1]
    info = {}
    with newest.open(encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            notes = row["ADA Notes"] if row["ADA Notes"] not in ("", "NaN") else ""
            info[row["GTFS Stop ID"]] = {
                "borough": BOROUGHS.get(row["Borough"], row["Borough"]),
                "line": row["Line"],
                "division": row["Division"],
                "structure": row["Structure"],
                "accessible": ACCESSIBLE.get(row["ADA"], "") + (f" ({notes})" if notes else ""),
                "north": row["North Direction Label"],
                "south": row["South Direction Label"],
            }
    body = json.dumps(info, separators=(",", ":"), ensure_ascii=False, sort_keys=True)
    OUT.write_text("// Generated by build_station_info.py from the MTA Subway Stations dataset. Do not edit.\n"
                   f"const STATION_INFO = {body};\n", encoding="utf-8")
    print(f"Wrote {OUT}: {len(info)} stations, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
