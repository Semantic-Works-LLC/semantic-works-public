#!/usr/bin/env python3
"""Build site/index.html: index.template.html with the modules from js/ inlined into its one script.

The page has to work as a single file opened straight from disk, so the modules are not imported;
their text is copied in, unchanged, in the order listed in js/modules.txt. Each one is preceded by
a comment naming the file it came from.

    python3 build.py           write site/index.html
    python3 build.py --check   also confirm every module appears in it exactly as in its source file

Standard library only.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).parent
TEMPLATE = ROOT / "index.template.html"
MODULES = ROOT / "js" / "modules.txt"
OUTPUT = ROOT / "site" / "index.html"
MARKER = "/* @inline js/modules.txt */\n"
NOTICE = "<!-- Generated by build.py from index.template.html and js/. Edit those, then run `make build`. -->\n"


def module_names():
    lines = MODULES.read_text(encoding="utf-8").splitlines()
    return [line.strip() for line in lines if line.strip() and not line.startswith("#")]


def banner(name):
    return f"// ===== js/{name} =====\n"


def build():
    template = TEMPLATE.read_text(encoding="utf-8")
    if template.count(MARKER) != 1:
        raise SystemExit(f"{TEMPLATE.name} must contain the line {MARKER.strip()!r} exactly once")
    parts = []
    for name in module_names():
        source = (MODULES.parent / name).read_text(encoding="utf-8")
        if "</script" in source:
            raise SystemExit(f"js/{name} contains '</script', which would end the inlined script early")
        parts.append(banner(name) + source + ("" if source.endswith("\n") else "\n"))
    first_line, rest = template.split("\n", 1)   # the notice goes right after <!doctype html>
    return first_line + "\n" + NOTICE + rest.replace(MARKER, "\n".join(parts))


def check(page):
    """Every module must sit in the page byte for byte as in its file, in the listed order."""
    position = 0
    for name in module_names():
        source = (MODULES.parent / name).read_text(encoding="utf-8")
        found = page.find(banner(name) + source, position)
        if found < 0:
            raise SystemExit(f"FAILED: js/{name} is not in {OUTPUT.name} exactly as in its source file")
        position = found + len(source)
    print(f"Checked: all {len(module_names())} modules are in {OUTPUT.name} unchanged and in order.")


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    page = build()
    OUTPUT.parent.mkdir(exist_ok=True)
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != page:
        OUTPUT.write_text(page, encoding="utf-8")
        print(f"Built {OUTPUT.relative_to(ROOT)} from {len(module_names())} modules.")
    else:
        print(f"{OUTPUT.relative_to(ROOT)} is up to date.")
    if "--check" in argv:
        check(OUTPUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
