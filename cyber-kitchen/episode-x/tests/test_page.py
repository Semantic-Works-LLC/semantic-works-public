"""The page as a whole: how it is built, laid out and reloaded.

The tests for each JavaScript module are in tests/js/, one file per module in js/ (the Process Map has
two). The tests named after what Pavel asked for are in tests/test_requirements.py, and the screenshots
are taken in tests/test_screenshots.py.
"""
import re

import pytest

from tests.conftest import PROJECT, open_page
from tests.support import click, run, settle, show

HTML = (PROJECT / "site" / "index.html").read_text(encoding="utf-8")
MODULES = [line for line in (PROJECT / "js" / "modules.txt").read_text(encoding="utf-8").split() if line.endswith(".js")]


# ---------- how the page is built ----------

def test_the_page_is_generated_and_says_so(page):
    assert HTML.split("\n")[1].startswith("<!-- Generated by build.py")


def test_every_module_is_inlined_unchanged_and_in_order():
    position = 0
    for name in MODULES:
        source = (PROJECT / "js" / name).read_text(encoding="utf-8")
        found = HTML.find(f"// ===== js/{name} =====\n" + source, position)
        assert found > position, f"js/{name} is not in the page exactly as in its file"
        position = found
    assert len(MODULES) == 23 and HTML.count("<script>") == 1


def test_every_module_has_a_test_file_and_every_test_file_a_module():
    tests = {path.name for path in (PROJECT / "tests" / "js").glob("test_*.py")}
    for name in MODULES:
        assert f"test_{name[:-3].replace('-', '_')}.py" in tests, name
    assert tests - {f"test_{name[:-3].replace('-', '_')}.py" for name in MODULES} == {"test_des_graph_pin.py"}
    assert sorted(path.name for path in (PROJECT / "js").glob("*.js")) == sorted(MODULES), "no module file is left out of the page"


def test_modules_do_not_define_the_same_name_twice():
    """All modules share one script, so a name declared in two of them would stop the page loading."""
    seen = {}
    for name in MODULES:
        for found in re.findall(r"^(?:const|let|class|function) +([A-Za-z_$][\w$]*)", (PROJECT / "js" / name).read_text(encoding="utf-8"), re.M):
            assert found not in seen, f"{found} is declared in both js/{seen.get(found)} and js/{name}"
            seen[found] = name


def test_page_loads_nothing_from_the_internet(page):
    resources = page.evaluate("performance.getEntriesByType('resource').map(r => r.name)")
    origin = page.evaluate("location.origin")
    assert all(name.startswith(origin) for name in resources)
    assert not re.search(r"<(script|link|img)[^>]+(src|href)=\"(?!data:)", HTML)
    assert "@import" not in HTML and not re.search(r"^\s*import ", "".join((PROJECT / "js" / name).read_text() for name in MODULES), re.M)


def test_the_built_page_runs_straight_from_disk_without_a_server(browser):
    page, finish = open_page(browser, (PROJECT / "site" / "index.html").as_uri(), init_script=None)
    page.wait_for_timeout(300)
    assert page.evaluate("clock") > 0 and page.title() == "Semantic Works: Cyber Kitchen"
    finish()


def test_a_long_run_stays_free_of_errors_on_every_view(page):
    """Ten simulated minutes on each view, with the panel open and something selected; the page fixture fails on any error."""
    page.evaluate("setPanel(true); setFold('events', true); setFold('legend', true)")
    for view, info in [("des", "DES_RES.tables.units[0].info"), ("graph", "DES_TASKS.plating.info"), ("score", "SCORE[8].info")]:
        show(page, view)
        page.evaluate(f"select({info}); setTab('metrics')")
        for _ in range(20):
            run(page, 30, dt=0.1)
            page.evaluate("renderMetrics(); renderEvents(); renderActions(); updateActorList()")
    assert page.evaluate("desEngine.eventsProcessed") > 3000 and page.evaluate("clock") > 1790


# ---------- page structure and layout ----------

def test_title_and_heading(page):
    assert page.title() == "Semantic Works: Cyber Kitchen"
    assert page.locator("h1").inner_text() == "Semantic Works: Cyber Kitchen"


def test_the_page_is_exactly_one_screen_tall_and_as_wide_as_the_window(page):
    box = page.locator("main").bounding_box()
    assert (box["x"], box["y"], box["width"], box["height"]) == (0, 0, 1400, 900)
    card = page.locator(".view-card").bounding_box()
    assert card["width"] == 1400 - 32 and card["y"] + card["height"] == 900 - 16
    assert page.evaluate("document.documentElement.scrollHeight") == 900


def test_opening_the_panel_narrows_the_view_but_keeps_its_height(page):
    before = page.locator(".view-card").bounding_box()
    page.click("#panel-toggle")
    page.wait_for_timeout(400)
    after, panel = page.locator(".view-card").bounding_box(), page.locator(".panel-inner").bounding_box()
    assert after["height"] == before["height"] == panel["height"]
    assert after["width"] == pytest.approx(before["width"] - 340 - 12, abs=1)
    assert round(panel["x"] + panel["width"]) == 1400 - 16


def test_the_panel_scrolls_inside_itself(page):
    page.evaluate("select(DES_TASKS.plating.info); setTab('metrics'); setFold('events', true); setFold('legend', true)")
    page.wait_for_timeout(400)
    assert page.evaluate("document.documentElement.scrollHeight") == 900
    assert page.evaluate("(() => { const inner = document.querySelector('.panel-inner'); return inner.scrollHeight > inner.clientHeight; })()")


def test_all_three_views_take_the_same_space(page):
    boxes = []
    for view, node in [("des", "desview"), ("graph", "desgraph"), ("score", "scoreview")]:
        show(page, view)
        boxes.append(page.locator(f"#{node}").bounding_box())
    assert boxes[0] == boxes[1] == boxes[2]


def test_narrow_screens_stack_the_panel_under_the_view(browser, site_server):
    page, finish = open_page(browser, site_server[0], width=600, height=900)
    page.click("#panel-toggle")
    view, panel = page.locator(".view-card").bounding_box(), page.locator(".panel-inner").bounding_box()
    assert panel["y"] >= view["y"] + view["height"] and panel["width"] == view["width"]
    assert page.evaluate("getComputedStyle($('panel-divider')).display") == "none"
    finish()


def test_the_selected_object_is_outlined_in_light_grey_on_every_view(page):
    select = "#e3e1d6"
    assert page.evaluate("getComputedStyle(document.documentElement).getPropertyValue('--select').trim()") == select
    # on the Scorecard the outline is a ring just outside the tile, so the tile keeps its own coloured edge
    for view, expression, outline in [("des", "DES_RES.oven.units[0].info.nodes[0].querySelector('rect')", None), ("graph", "GRAPH.oven.g.querySelector('rect')", None),
                                      ("score", "SCORE[0].box", "SCORE[0].box.parentNode.querySelector('.score-ring')")]:
        show(page, view)
        click(page, expression)
        outline = outline or expression
        assert page.evaluate(f"(() => {{ const s = getComputedStyle({outline}); return [s.stroke, s.strokeWidth]; }})()") == ["rgb(227, 225, 214)", "2.5px"], view
    assert page.evaluate("getComputedStyle(SCORE[0].box).stroke") != "rgb(227, 225, 214)", "the selected tile's own edge still shows"
    assert page.evaluate("getComputedStyle(SCORE[1].box.parentNode.querySelector('.score-ring')).display") == "none"


def test_tabs_and_picker_rows_use_the_selection_grey(page):
    page.evaluate("select(DES_TASKS.oven.info)")
    assert page.evaluate("getComputedStyle(document.querySelector('#tabs [aria-selected=true]')).borderBottomColor") == "rgb(227, 225, 214)"


# ---------- live reload ----------

def test_page_reloads_itself_when_a_site_file_changes(browser, site_server):
    url, root = site_server
    page, finish = open_page(browser, url, init_script=None)
    page.evaluate("window.loadedBefore = true")
    page.wait_for_timeout(300)
    index = root / "index.html"
    with page.expect_navigation(timeout=10_000):
        index.write_text(index.read_text(encoding="utf-8") + "\n<!-- touched by test -->", encoding="utf-8")
    assert page.evaluate("typeof window.loadedBefore") == "undefined"
    assert page.title() == "Semantic Works: Cyber Kitchen"
    page.wait_for_timeout(300)   # let the real animation loop run a few frames
    assert page.evaluate("clock") > 0
    finish()
